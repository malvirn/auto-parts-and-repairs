create table if not exists public.customer_overpayment_credit_notes (
  id uuid primary key default gen_random_uuid(),
  note_number bigint generated by default as identity unique,
  overpayment_credit_id uuid not null unique references public.customer_overpayment_credits(id) on delete restrict,
  customer_id uuid references public.customers(id) on delete set null,
  invoice_id uuid references public.invoices(id) on delete set null,
  customer_name text not null,
  customer_phone text,
  amount numeric(12,2) not null check (amount > 0),
  issued_at timestamptz not null default now(),
  issued_by uuid references auth.users(id)
);

alter table public.customer_overpayment_credit_notes enable row level security;
drop policy if exists customer_overpayment_credit_notes_read on public.customer_overpayment_credit_notes;
create policy customer_overpayment_credit_notes_read on public.customer_overpayment_credit_notes
for select to authenticated using (public.current_access_level() >= 1);
revoke all on public.customer_overpayment_credit_notes from anon, authenticated;
grant select on public.customer_overpayment_credit_notes to authenticated;
grant usage, select on all sequences in schema public to authenticated;

create or replace function public.issue_overpayment_credit_note(p_overpayment_credit_id uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  credit_row public.customer_overpayment_credits%rowtype;
  note_row public.customer_overpayment_credit_notes%rowtype;
begin
  if auth.uid() is null or public.current_access_level() < 2 then
    raise exception 'Only Accounting or Super Admin can issue an overpayment credit note';
  end if;
  select * into credit_row from public.customer_overpayment_credits
  where id = p_overpayment_credit_id for update;
  if not found then raise exception 'Customer overpayment credit not found'; end if;
  if coalesce(credit_row.available_amount, 0) <= 0.005 then
    raise exception 'There is no available overpayment to issue a credit note for';
  end if;
  insert into public.customer_overpayment_credit_notes
    (overpayment_credit_id, customer_id, invoice_id, customer_name, customer_phone, amount, issued_by)
  values
    (credit_row.id, credit_row.customer_id, credit_row.invoice_id,
     coalesce(nullif(credit_row.customer_name,''),'Customer'), credit_row.customer_phone,
     credit_row.available_amount, auth.uid())
  on conflict (overpayment_credit_id) do update set overpayment_credit_id = excluded.overpayment_credit_id
  returning * into note_row;
  return jsonb_build_object('id', note_row.id, 'credit_note_number', note_row.note_number,
    'customer_name', note_row.customer_name, 'amount', note_row.amount,
    'issued_at', note_row.issued_at, 'invoice_id', note_row.invoice_id);
end;
$$;
revoke all on function public.issue_overpayment_credit_note(uuid) from public, anon;
grant execute on function public.issue_overpayment_credit_note(uuid) to authenticated;