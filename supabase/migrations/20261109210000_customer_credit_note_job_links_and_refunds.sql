
-- Customer overpayment credit note job-card links and refunds.
create table if not exists public.customer_overpayment_credit_job_links (
 id uuid primary key default gen_random_uuid(),
 credit_note_id uuid not null unique references public.customer_overpayment_credit_notes(id) on delete restrict,
 repair_job_id uuid not null references public.repair_jobs(id) on delete restrict,
 linked_by uuid references auth.users(id),
 linked_at timestamptz not null default now()
);
create table if not exists public.customer_overpayment_credit_refunds (
 id uuid primary key default gen_random_uuid(),
 refund_number bigint generated by default as identity unique,
 credit_note_id uuid not null references public.customer_overpayment_credit_notes(id) on delete restrict,
 overpayment_credit_id uuid not null references public.customer_overpayment_credits(id) on delete restrict,
 amount numeric(12,2) not null check (amount > 0),
 payment_date date not null default current_date,
 payment_method text not null,
 account_id uuid not null references public.accounts(id),
 journal_entry_id uuid not null references public.journal_entries(id) on delete restrict,
 created_by uuid references auth.users(id),
 created_at timestamptz not null default now()
);
alter table public.customer_overpayment_credit_job_links enable row level security;
alter table public.customer_overpayment_credit_refunds enable row level security;
drop policy if exists customer_overpayment_credit_job_links_read on public.customer_overpayment_credit_job_links;
create policy customer_overpayment_credit_job_links_read on public.customer_overpayment_credit_job_links for select to authenticated using (public.current_access_level() >= 1);
drop policy if exists customer_overpayment_credit_refunds_read on public.customer_overpayment_credit_refunds;
create policy customer_overpayment_credit_refunds_read on public.customer_overpayment_credit_refunds for select to authenticated using (public.current_access_level() >= 1);
grant select on public.customer_overpayment_credit_job_links, public.customer_overpayment_credit_refunds to authenticated;

create or replace function public.link_overpayment_credit_to_job(p_credit_note_id uuid, p_repair_job_id uuid)
returns uuid language plpgsql security definer set search_path=pg_catalog,public as $$
declare n public.customer_overpayment_credit_notes%rowtype; c public.customer_overpayment_credits%rowtype; j public.repair_jobs%rowtype; original_invoice public.invoices%rowtype; customer_row public.customers%rowtype; link_id uuid;
begin
 if auth.uid() is null or public.current_access_level() < 2 then raise exception 'Only authorised accounting users can link customer credit notes'; end if;
 select * into n from public.customer_overpayment_credit_notes where id=p_credit_note_id for update;
 if not found then raise exception 'Credit note not found'; end if;
 select * into c from public.customer_overpayment_credits where id=n.overpayment_credit_id for update;
 if not found then raise exception 'Customer credit balance not found'; end if;
 select * into original_invoice from public.invoices where id=n.invoice_id;
 select * into j from public.repair_jobs where id=p_repair_job_id;
 if not found then raise exception 'Job card not found'; end if;
 select * into customer_row from public.customers where id=j.customer_id;
 if not found then raise exception 'The job card customer could not be found'; end if;
 if j.checklist_number is null then raise exception 'This job card has no checklist number yet'; end if;
 if coalesce(j.customer_id::text,'') <> coalesce(n.customer_id::text,'')
    or lower(trim(coalesce(customer_row.full_name,''))) <> lower(trim(coalesce(n.customer_name,'')))
    or regexp_replace(coalesce(customer_row.phone,''),'[^0-9]','','g') <> regexp_replace(coalesce(n.customer_phone,''),'[^0-9]','','g')
    or lower(trim(coalesce(customer_row.email,''))) <> lower(trim(coalesce(original_invoice.customer_email,''))) then
  raise exception 'Customer details do not match. Name, email and phone must match the original credit note customer.';
 end if;
 if coalesce(c.available_amount,0) <= 0 then raise exception 'This credit note has no remaining balance'; end if;
 insert into public.customer_overpayment_credit_job_links(credit_note_id,repair_job_id,linked_by)
 values(p_credit_note_id,p_repair_job_id,auth.uid())
 on conflict(credit_note_id) do update set repair_job_id=excluded.repair_job_id,linked_by=excluded.linked_by,linked_at=now()
 returning id into link_id;
 return link_id;
end $$;

create or replace function public.refund_overpayment_credit(p_credit_note_id uuid,p_amount numeric,p_account_id uuid,p_payment_date date,p_payment_method text)
returns uuid language plpgsql security definer set search_path=pg_catalog,public as $$
declare n public.customer_overpayment_credit_notes%rowtype; c public.customer_overpayment_credits%rowtype; cash_account public.accounts%rowtype; liability_account public.accounts%rowtype; entry_id uuid; refund_id uuid; amount_to_refund numeric(12,2);
begin
 if auth.uid() is null or public.current_access_level() < 2 then raise exception 'Only authorised accounting users can refund customer credit'; end if;
 amount_to_refund:=round(coalesce(p_amount,0),2);
 if amount_to_refund <= 0 or p_payment_date is null or nullif(trim(p_payment_method),'') is null then raise exception 'Enter a valid refund amount, date and payment method'; end if;
 select * into n from public.customer_overpayment_credit_notes where id=p_credit_note_id for update;
 if not found then raise exception 'Credit note not found'; end if;
 select * into c from public.customer_overpayment_credits where id=n.overpayment_credit_id for update;
 if not found then raise exception 'Customer credit balance not found'; end if;
 if amount_to_refund > coalesce(c.available_amount,0)+0.005 then raise exception 'Refund exceeds the remaining credit balance of %', c.available_amount; end if;
 select * into cash_account from public.accounts where id=p_account_id and is_active=true and type='asset' and code like '10%';
 if not found then raise exception 'Choose an active cash or bank asset account'; end if;
 select * into liability_account from public.accounts where code='2300' and is_active=true and type='liability';
 if not found then raise exception 'Customer credit liability account 2300 is missing or inactive'; end if;
 insert into public.journal_entries(entry_date,reference,description,source_type,source_id,created_by)
 values(p_payment_date,'CN-'||lpad(n.note_number::text,5,'0'),'Customer credit refund — '||n.customer_name,'customer_credit_refund',n.id,auth.uid()) returning id into entry_id;
 insert into public.journal_lines(journal_entry_id,account_id,debit,credit,memo) values(entry_id,liability_account.id,amount_to_refund,0,'Refund of customer credit note');
 insert into public.journal_lines(journal_entry_id,account_id,debit,credit,memo) values(entry_id,cash_account.id,0,amount_to_refund,'Customer refund paid');
 update public.customer_overpayment_credits set available_amount=round(available_amount-amount_to_refund,2) where id=c.id;
 insert into public.customer_overpayment_credit_refunds(credit_note_id,overpayment_credit_id,amount,payment_date,payment_method,account_id,journal_entry_id,created_by)
 values(n.id,c.id,amount_to_refund,p_payment_date,trim(p_payment_method),cash_account.id,entry_id,auth.uid()) returning id into refund_id;
 return refund_id;
end $$;
revoke all on function public.link_overpayment_credit_to_job(uuid,uuid) from public;
revoke all on function public.refund_overpayment_credit(uuid,numeric,uuid,date,text) from public;
grant execute on function public.link_overpayment_credit_to_job(uuid,uuid) to authenticated;
grant execute on function public.refund_overpayment_credit(uuid,numeric,uuid,date,text) to authenticated;
