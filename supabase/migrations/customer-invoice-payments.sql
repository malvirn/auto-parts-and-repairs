begin;

create table if not exists public.invoices (
  id uuid primary key default gen_random_uuid(),
  invoice_number bigint generated by default as identity unique,
  customer_id uuid references public.customers(id) on delete set null,
  customer_name text not null default '',
  customer_phone text,
  customer_email text,
  items jsonb not null default '[]'::jsonb,
  discount numeric(12, 2) not null default 0,
  vat_rate numeric(5, 2) not null default 0,
  subtotal numeric(12, 2) not null default 0,
  total numeric(12, 2) not null default 0,
  amount_paid numeric(12, 2) not null default 0,
  notes text,
  reference text,
  due_date date,
  status text not null default 'unpaid',
  issued_at timestamptz not null default now()
);

alter table public.invoices
  add column if not exists invoice_number bigint generated by default as identity,
  add column if not exists customer_id uuid references public.customers(id) on delete set null,
  add column if not exists customer_name text not null default '',
  add column if not exists customer_phone text,
  add column if not exists customer_email text,
  add column if not exists items jsonb not null default '[]'::jsonb,
  add column if not exists discount numeric(12, 2) not null default 0,
  add column if not exists vat_rate numeric(5, 2) not null default 0,
  add column if not exists subtotal numeric(12, 2) not null default 0,
  add column if not exists total numeric(12, 2) not null default 0,
  add column if not exists amount_paid numeric(12, 2) not null default 0,
  add column if not exists notes text,
  add column if not exists reference text,
  add column if not exists due_date date,
  add column if not exists status text not null default 'unpaid',
  add column if not exists issued_at timestamptz not null default now();

create unique index if not exists invoices_invoice_number_uidx
  on public.invoices(invoice_number);

alter table public.invoices enable row level security;
revoke all on public.invoices from anon, authenticated;
grant select, insert on public.invoices to authenticated;

drop policy if exists "Accounting users can manage customer invoices" on public.invoices;
drop policy if exists "Accounting users can view customer invoices" on public.invoices;
drop policy if exists "Accounting users can create customer invoices" on public.invoices;
create policy "Accounting users can view customer invoices"
  on public.invoices for select
  to authenticated
  using (public.current_access_level() >= 2);
create policy "Accounting users can create customer invoices"
  on public.invoices for insert
  to authenticated
  with check (
    public.current_access_level() >= 2
    and coalesce(amount_paid, 0) = 0
    and status = 'unpaid'
  );

create table if not exists public.invoice_payments (
  id uuid primary key default gen_random_uuid(),
  invoice_id uuid not null references public.invoices(id) on delete cascade,
  amount numeric(12, 2) not null check (amount > 0),
  payment_date date not null default current_date,
  payment_method text not null,
  journal_entry_id uuid references public.journal_entries(id) on delete set null,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists invoice_payments_invoice_date_idx
  on public.invoice_payments(invoice_id, payment_date desc);

alter table public.invoice_payments enable row level security;
revoke all on table public.invoice_payments from anon, authenticated;
grant select on table public.invoice_payments to authenticated;

drop policy if exists "Accounting users can view invoice payments" on public.invoice_payments;
create policy "Accounting users can view invoice payments"
  on public.invoice_payments for select
  to authenticated
  using (public.current_access_level() >= 2);

create or replace function public.record_customer_invoice_payment(
  p_invoice_id uuid,
  p_amount numeric,
  p_account_id uuid,
  p_payment_date date default current_date
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  invoice_row public.invoices%rowtype;
  cash_account public.accounts%rowtype;
  receivable_account public.accounts%rowtype;
  entry_id uuid;
  new_amount_paid numeric(12, 2);
begin
  if auth.uid() is null or public.current_access_level() < 2 then
    raise exception 'Only authorised accounting users can record invoice payments';
  end if;

  if p_amount is null or p_amount <= 0 then
    raise exception 'Payment amount must be greater than zero';
  end if;

  if p_payment_date is null then
    raise exception 'Payment date is required';
  end if;

  select * into invoice_row
  from public.invoices
  where id = p_invoice_id
  for update;

  if not found then
    raise exception 'Customer invoice not found';
  end if;

  select * into cash_account
  from public.accounts
  where id = p_account_id and is_active = true and type = 'asset' and code like '10%';

  if not found then
    raise exception 'Choose an active cash or bank account';
  end if;

  select * into receivable_account
  from public.accounts
  where code = '1100' and is_active = true;

  if not found then
    raise exception 'Accounts Receivable (account code 1100) is missing or inactive';
  end if;

  if p_amount > greatest(0, invoice_row.total - coalesce(invoice_row.amount_paid, 0)) + 0.005 then
    raise exception 'Payment exceeds the invoice balance of %', greatest(0, invoice_row.total - coalesce(invoice_row.amount_paid, 0));
  end if;

  new_amount_paid := round(coalesce(invoice_row.amount_paid, 0) + p_amount, 2);

  insert into public.journal_entries (entry_date, reference, description, source_type)
  values (
    p_payment_date,
    'INV-' || lpad(invoice_row.invoice_number::text, 5, '0'),
    'Customer invoice payment — ' || invoice_row.customer_name,
    'customer_invoice_payment'
  )
  returning id into entry_id;

  insert into public.journal_lines (journal_entry_id, account_id, debit, credit)
  values
    (entry_id, cash_account.id, p_amount, 0),
    (entry_id, receivable_account.id, 0, p_amount);

  insert into public.invoice_payments (
    invoice_id, amount, payment_date, payment_method, journal_entry_id, created_by
  )
  values (
    invoice_row.id, p_amount, p_payment_date, cash_account.name, entry_id, auth.uid()
  );

  update public.invoices
  set amount_paid = new_amount_paid,
      status = case when new_amount_paid >= total - 0.005 then 'paid' else 'partially_paid' end
  where id = invoice_row.id;

  return entry_id;
end;
$$;

revoke all on function public.record_customer_invoice_payment(uuid, numeric, uuid, date) from public;
grant execute on function public.record_customer_invoice_payment(uuid, numeric, uuid, date) to authenticated;

create or replace view public.customer_account_statement
with (security_invoker = true)
as
with repair_payment_totals as (
  select repair_job_id, sum(amount) as paid_amount
  from public.repair_job_payments
  group by repair_job_id
),
sales_receipt_totals as (
  select sales_order_id, max(amount) as paid_amount
  from public.receipts
  where sales_order_id is not null
  group by sales_order_id
),
invoice_payment_totals as (
  select invoice_id, sum(amount) as paid_amount
  from public.invoice_payments
  group by invoice_id
)
select
  c.id as customer_id,
  c.full_name as customer_name,
  c.phone,
  c.email,
  j.id as source_id,
  'Repair job'::text as source_type,
  coalesce(j.cro_number, 'Job #' || lpad(j.job_number::text, 4, '0')) as reference,
  j.created_at::date as entry_date,
  coalesce(j.total_cost, 0)::numeric(12, 2) as total_amount,
  coalesce(rp.paid_amount, 0)::numeric(12, 2) as amount_paid,
  (coalesce(j.total_cost, 0) - coalesce(rp.paid_amount, 0))::numeric(12, 2) as balance_due
from public.repair_jobs j
join public.customers c on c.id = j.customer_id
left join repair_payment_totals rp on rp.repair_job_id = j.id
where coalesce(j.total_cost, 0) > 0
  and (
    j.status::text in ('Ready for Pickup', 'Unclaimed', 'Collected', 'Processed')
    or rp.repair_job_id is not null
  )

union all

select
  c.id as customer_id,
  c.full_name as customer_name,
  c.phone,
  c.email,
  so.id as source_id,
  'Sales order'::text as source_type,
  'Order #' || lpad(so.order_number::text, 4, '0') as reference,
  so.created_at::date as entry_date,
  coalesce(so.total_usd, 0)::numeric(12, 2) as total_amount,
  coalesce(sr.paid_amount, 0)::numeric(12, 2) as amount_paid,
  (coalesce(so.total_usd, 0) - coalesce(sr.paid_amount, 0))::numeric(12, 2) as balance_due
from public.sales_orders so
join public.customers c on c.id = so.customer_id
left join sales_receipt_totals sr on sr.sales_order_id = so.id
where so.status = 'Confirmed'
  and coalesce(so.total_usd, 0) > 0

union all

select
  c.id as customer_id,
  c.full_name as customer_name,
  c.phone,
  c.email,
  invoice.id as source_id,
  'Invoice'::text as source_type,
  'INV-' || lpad(invoice.invoice_number::text, 5, '0') as reference,
  invoice.issued_at::date as entry_date,
  coalesce(invoice.total, 0)::numeric(12, 2) as total_amount,
  coalesce(payments.paid_amount, 0)::numeric(12, 2) as amount_paid,
  (coalesce(invoice.total, 0) - coalesce(payments.paid_amount, 0))::numeric(12, 2) as balance_due
from public.invoices invoice
join public.customers c on c.id = invoice.customer_id
left join invoice_payment_totals payments on payments.invoice_id = invoice.id
where coalesce(invoice.total, 0) > 0;

revoke all on public.customer_account_statement from public, anon;
grant select on public.customer_account_statement to authenticated;

commit;
