create or replace function public.record_repair_status()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.status_history (job_id, status)
    values (new.id, new.status);
  elsif old.status is distinct from new.status then
    insert into public.status_history (job_id, status)
    values (new.id, new.status);
  end if;
  return new;
end;
$$;

drop trigger if exists repair_jobs_status_history on public.repair_jobs;
create trigger repair_jobs_status_history
after insert or update of status on public.repair_jobs
for each row execute function public.record_repair_status();

create or replace function public.lookup_repair_portal(
  p_phone text,
  p_license_plate text,
  p_job_number integer default null,
  p_token text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  result jsonb;
begin
  select jsonb_build_object(
    'job_number', r.job_number,
    'status', r.status,
    'total_cost', r.total_cost,
    'created_at', r.created_at,
    'completed_at', r.completed_at,
    'collected_at', r.collected_at,
    'customer_name', c.full_name,
    'vehicle', jsonb_build_object(
      'make', v.make,
      'model', v.model,
      'year', v.year,
      'body_type', v.body_type,
      'license_plate', v.license_plate
    ),
    'timeline', coalesce((
      select jsonb_agg(
        jsonb_build_object('status', h.status, 'created_at', h.created_at)
        order by h.created_at
      )
      from public.status_history h
      where h.job_id = r.id
    ), '[]'::jsonb)
  )
  into result
  from public.repair_jobs r
  join public.customers c on c.id = r.customer_id
  join public.vehicles v on v.id = r.vehicle_id
  where (
    (
      p_token is not null
      and p_job_number is not null
      and r.job_number = p_job_number
      and r.portal_token = p_token
    )
    or (
      p_token is null
      and nullif(trim(p_phone), '') is not null
      and nullif(trim(p_license_plate), '') is not null
      and regexp_replace(coalesce(c.phone, ''), '\\D', '', 'g') = regexp_replace(coalesce(p_phone, ''), '\\D', '', 'g')
      and lower(regexp_replace(coalesce(v.license_plate, ''), '\\s', '', 'g')) = lower(regexp_replace(coalesce(p_license_plate, ''), '\\s', '', 'g'))
    )
  )
  limit 1;

  return result;
end;
$$;

