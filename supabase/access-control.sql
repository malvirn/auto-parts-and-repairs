-- Atomically reserve stock for a repair job so stock cannot go negative when
-- two staff users try to use the last units at the same time.
create or replace function public.consume_part_stock(p_part_id uuid, p_quantity integer)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  updated_count integer;
begin
  if p_quantity is null or p_quantity < 1 then
    return false;
  end if;

  update public.parts
  set quantity_in_stock = quantity_in_stock - p_quantity
  where id = p_part_id
    and quantity_in_stock >= p_quantity;

  get diagnostics updated_count = row_count;
  return updated_count = 1;
end;
$$;

create or replace function public.restore_part_stock(p_part_id uuid, p_quantity integer)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  updated_count integer;
begin
  update public.parts
  set quantity_in_stock = quantity_in_stock + greatest(coalesce(p_quantity, 0), 0)
  where id = p_part_id;

  get diagnostics updated_count = row_count;
  return updated_count = 1;
end;
$$;

revoke all on function public.consume_part_stock(uuid, integer) from public;
revoke all on function public.restore_part_stock(uuid, integer) from public;
grant execute on function public.consume_part_stock(uuid, integer) to anon, authenticated;
grant execute on function public.restore_part_stock(uuid, integer) to anon, authenticated;

-- Quotations and amendable sales orders. Prices are snapshots so later shop
-- price changes do not rewrite an issued customer document.
create table if not exists public.quotations (
  id uuid primary key default gen_random_uuid(),
  quotation_number bigint generated by default as identity unique,
  customer_id uuid not null references public.customers(id) on delete restrict,
  repair_job_id uuid references public.repair_jobs(id) on delete set null,
  status text not null default 'Draft',
  markup_pct numeric(5, 2) not null default 25.00,
  usd_to_zig_rate numeric(12, 4) not null,
  total_usd numeric(12, 2) not null default 0,
  total_zig numeric(14, 2) not null default 0,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.quotation_items (
  id uuid primary key default gen_random_uuid(),
  quotation_id uuid not null references public.quotations(id) on delete cascade,
  part_id uuid references public.parts(id) on delete set null,
  part_name text not null,
  quantity integer not null check (quantity > 0),
  cost_price_usd numeric(12, 2) not null default 0,
  markup_pct numeric(5, 2) not null default 25.00,
  unit_price_usd numeric(12, 2) not null default 0,
  total_usd numeric(12, 2) not null default 0,
  unit_price_zig numeric(14, 2) not null default 0,
  total_zig numeric(14, 2) not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.sales_orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  quotation_id uuid references public.quotations(id) on delete set null,
  customer_id uuid not null references public.customers(id) on delete restrict,
  repair_job_id uuid references public.repair_jobs(id) on delete set null,
  status text not null default 'Draft',
  usd_to_zig_rate numeric(12, 4) not null default 26.6908,
  total_usd numeric(12, 2) not null default 0,
  total_zig numeric(14, 2) not null default 0,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sales_order_items (
  id uuid primary key default gen_random_uuid(),
  sales_order_id uuid not null references public.sales_orders(id) on delete cascade,
